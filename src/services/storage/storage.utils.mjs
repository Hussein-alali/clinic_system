// These functions never touch the network. Keep them side-effect free so
// they can be unit-tested in isolation (see tests/storage.utils.test.mjs).
// The browser build (storage.service.jsx) re-implements `isSafeKey` /
// `sanitizeFileName` verbatim because the app loads plain <script> tags,
// not ES modules; the two copies MUST stay in sync (tests enforce the
// behavior, not the sharing).
