// Validate an object key before it is signed or copied. Rejects anything
// that could escape the intended prefix (path traversal) or is malformed.
export function isSafeKey(key) {
  if (!key || typeof key !== "string") return false;
  if (key.length > 1024) return false;
  if (key.startsWith("/")) return false; // keys are relative
  if (key.includes("\\")) return false; // no Windows separators
  for (let i = 0; i < key.length; i++) {
    const c = key.charCodeAt(i);
    if (c < 0x20 || c === 0x7f) return false; // no control chars / NUL
  }
  const segs = key.split("/");
  for (const s of segs) {
    if (s === "" || s === "." || s === "..") return false;
  }
  return true;
}

// Throwing variant used at call sites that must have a valid key.
export function requireSafeKey(key) {
  if (!isSafeKey(key)) {
    const err = new Error("invalid_key");
    err.code = "invalid_key";
    throw err;
  }
  return key;
}

// Sanitize an uploaded filename. Mirrors src/supabase.jsx:sanitizeFileName
// so keys generated by the app and by any tooling match byte-for-byte.
// Keeps word chars, dots, hyphens and the Arabic block; collapses the rest.
export function sanitizeFileName(name) {
  return String(name || "file").replace(/[^\w.\-؀-ۿ]+/g, "_").slice(0, 120);
}

// Percent-encode a key for an S3/R2 URL path, preserving the "/" separators.
export function encodeKey(key) {
  return String(key).split("/").map(encodeURIComponent).join("/");
}

// Does a stored Supabase public URL correspond to this bucket/key?
// Used by the migration report to cross-check DB rows against objects.
export function parseSupabasePublicUrl(url) {
  if (typeof url !== "string") return null;
  const m = url.match(/\/storage\/v1\/object\/(?:public|sign)\/([^/]+)\/(.+?)(?:\?|$)/);
  if (!m) return null;
  let key;
  try { key = decodeURIComponent(m[2]); } catch { key = m[2]; }
  return { bucket: m[1], key };
}

// Clamp a requested signed-URL lifetime to policy (default 300s, max 3600s).
export function clampExpires(v, { def = 300, max = 3600 } = {}) {
  const n = Number(v);
  if (!Number.isFinite(n) || n <= 0) return def;
  return Math.min(Math.floor(n), max);
}

// Compare a source object against a destination object for verification.
// Returns { match, reason }. Size is the cheap primary signal; a checksum
// is only compared when both sides provide one (caller decides when to).
export function compareObjects(src, dest) {
  if (!dest || dest.exists === false) return { match: false, reason: "missing_in_destination" };
  if (src.size != null && dest.size != null && Number(src.size) !== Number(dest.size)) {
    return { match: false, reason: `size_mismatch:${src.size}!=${dest.size}` };
  }
  if (src.sha256 && dest.sha256 && src.sha256 !== dest.sha256) {
    return { match: false, reason: "checksum_mismatch" };
  }
  return { match: true, reason: "ok" };
}
